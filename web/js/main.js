function selectGap(id) {
  const gap = state.gaps.find((g) => g.id === id);
  if (!gap || gap.status !== 'open') return;
  state.selectedGapId = id;
  state.rightTab = 'gaps';
  state.expanded[id] = true;
  syncMarks();
  log('gap_selected', { gapId: id, n: gap.n });
  setBriefOpen(false); // the role brief has done its job once work starts
  changed('left', 'right');
  reveal('src');
}

registerRenderer('left', renderSynthesis);
registerRenderer('right', renderSources);
registerRenderer('leftStale', renderStale);

// ------------------------------------------------------- collapsible panels

const LAYOUT_KEY = 'sparring-partner:layout';

const STACKED = window.matchMedia('(max-width: 1180px)');

function applyLayout(layout) {
  for (const side of ['ai', 'src']) {
    const collapsed = Boolean(layout[side]);
    $('#app').classList.toggle(`${side}-collapsed`, collapsed);
    $(`#col-${side}`).classList.toggle('collapsed', collapsed);
    for (const btn of $$(`[data-collapse="${side}"]`)) btn.setAttribute('aria-expanded', String(!collapsed));
  }
}

function readLayout() {
  try { return JSON.parse(localStorage.getItem(LAYOUT_KEY)) || {}; } catch { return {}; }
}

let layout = {};

function setCollapsed(side, collapsed, { focus = false } = {}) {
  if (Boolean(layout[side]) === collapsed) return;
  layout = { ...layout, [side]: collapsed };
  applyLayout(layout);
  log('layout', { panel: side, collapsed });
  try { localStorage.setItem(LAYOUT_KEY, JSON.stringify(layout)); } catch { /* ignore */ }
  // Keep keyboard focus on the visible counterpart of the control that was used.
  if (focus) $(collapsed ? `#col-${side} .rail` : `#col-${side} .collapse-btn`)?.focus();
}

/** Make sure a side panel is visible (expanded, and on screen when panels are stacked). */
function reveal(side) {
  setCollapsed(side, false);
  if (STACKED.matches) $(`#col-${side}`).scrollIntoView({ behavior: 'smooth', block: 'start' });
}

function wireLayout() {
  layout = readLayout();
  applyLayout(layout);
  for (const btn of $$('[data-collapse]')) {
    btn.addEventListener('click', () => setCollapsed(btn.dataset.collapse, !layout[btn.dataset.collapse], { focus: true }));
  }
}

// ------------------------------------------------------------------ routing

function readHash() {
  const p = new URLSearchParams(location.hash.slice(1));
  return { caseId: p.get('case'), roleId: p.get('role'), mode: p.get('mode') };
}

function writeHash() {
  const p = new URLSearchParams({ case: state.caseId, role: state.roleId, mode: state.mode });
  history.replaceState(null, '', `#${p}`);
}

// ------------------------------------------------------------------ topbar

let cases = [];

function renderTopbar() {
  const select = $('#case-select');
  select.textContent = '';
  for (const c of cases) {
    const group = el('optgroup', { label: c.title });
    for (const r of c.roles) {
      group.append(el('option', {
        value: `${c.id}/${r.id}`,
        text: `${c.title} — ${r.name}`,
        selected: c.id === state.caseId && r.id === state.roleId,
      }));
    }
    select.append(group);
  }

  const demoBtn = $('#mode-demo'), liveBtn = $('#mode-live');
  demoBtn.setAttribute('aria-pressed', String(state.mode === 'demo'));
  liveBtn.setAttribute('aria-pressed', String(state.mode === 'live'));
  liveBtn.disabled = !hasModel();
  liveBtn.title = hasModel()
    ? `Answers generated by ${modelName()} from your case documents`
    : hasBackend()
      ? 'No model configured on the server (set ANTHROPIC_API_KEY and restart)'
      : 'Live mode needs the Python server (see README)';
  demoBtn.title = state.demo
    ? 'Prepared gaps and answers for this scenario, plus passage search'
    : 'Passage search only';
  $('#mode-note').textContent = state.mode === 'live' ? modelName() : state.demo ? '' : 'Passage search only';
}

// ------------------------------------------------------------------ loading

// Each load gets a number; a load that finishes after a newer one started (or
// after the user went back to the start screen) is dropped.
let loadSeq = 0;
const cancelLoads = () => { loadSeq++; document.body.classList.remove('loading'); };

async function loadSession({ caseId, roleId, mode }, { saveCurrent = true } = {}) {
  const seq = ++loadSeq;
  document.body.classList.add('loading');
  // The current session stays intact (and is what gets saved) until the new
  // case has fully loaded, so leaving mid-load can never overwrite saved work.
  if (saveCurrent) save();

  let data, demo;
  try {
    data = await loadCase(caseId, roleId);
    demo = await loadDemoScript(caseId, data.role.id);
  } catch (err) {
    if (seq === loadSeq) showFatal(`Could not load case “${caseId}”: ${err.message}`);
    return;
  }
  if (seq !== loadSeq) return;

  state.caseId = caseId;
  state.roleId = data.role.id;
  state.mode = mode === 'live' && hasModel() ? 'live' : 'demo';
  resetSession();
  state.caseData = data;
  state.docsById = Object.fromEntries(data.documents.map((d) => [d.id, d]));
  state.demo = demo;

  const restored = restore();
  if (!restored) log('session_started', { caseId, roleId: data.role.id, mode: state.mode });

  $('#role-brief-title').textContent = `${data.role.name}`;
  $('#role-brief-text').textContent = data.role.brief;
  renderStartHere(data);
  // Newcomers see the brief and the reading list; once gaps are found it makes room for the notes.
  setBriefOpen(!state.gapsChecked);

  loadNotes();
  writeHash();
  renderTopbar();
  renderSynthesis();
  renderSources();
  if (restored && (state.gapsChecked || state.insights.length)) setStatus('Session restored', 'ok');
  document.body.classList.remove('loading');
}

function renderStartHere(data) {
  const docs = (data.role.start_here || []).map((id) => state.docsById[id]).filter(Boolean);
  $('#start-here').hidden = !docs.length;
  $('#start-here-list').replaceChildren(...docs.map((d) => el('li', {}, el('span', {},
    el('button', {
      type: 'button',
      className: 'link-btn',
      text: d.title,
      title: `Open “${d.title}” in Source Documents`,
      onClick: () => { openInLibrary(d.id); reveal('src'); },
    }),
    el('span', { className: 'doc-type', text: d.kind })))));
}

function setBriefOpen(open) {
  $('#role-brief').toggleAttribute('open', open);
  $('#brief-toggle').setAttribute('aria-expanded', String(open));
}

// ------------------------------------------------------------------ start screen

async function renderHome() {
  const scripted = new Set(await demoScripts());
  const ordered = [...cases].sort((a, b) => Number(b.roles.some((r) => scripted.has(`${b.id}-${r.id}`))) - Number(a.roles.some((r) => scripted.has(`${a.id}-${r.id}`))));
  $('#home-cases').replaceChildren(...ordered.map((c) => el('article', { className: 'case-card' },
    el('h2', { text: c.title }),
    el('p', { text: c.summary }),
    el('div', { className: 'role-row' },
      el('span', { className: 'role-label', text: 'Play as' }),
      ...c.roles.map((r) => el('button', {
        type: 'button',
        className: 'role-btn',
        onClick: () => openCase(c.id, r.id),
      }, r.name, scripted.has(`${c.id}-${r.id}`) ? el('span', { className: 'demo-tag', text: 'scripted demo' }) : null))),
  )));
}

function showHome({ push = true } = {}) {
  cancelLoads();
  if (state.caseData) save();
  document.body.classList.add('at-home');
  $('#home').hidden = false;
  if (location.hash) {
    const url = location.pathname + location.search;
    if (push) history.pushState(null, '', url); else history.replaceState(null, '', url);
  }
  window.scrollTo(0, 0);
}

async function openCase(caseId, roleId, { push = true, mode = state.mode || 'demo' } = {}) {
  const first = !state.caseData;
  if (push) history.pushState(null, '', `#${new URLSearchParams({ case: caseId, role: roleId, mode })}`);
  document.body.classList.remove('at-home');
  $('#home').hidden = true;
  await loadSession({ caseId, roleId, mode }, { saveCurrent: !first });
  if (first) refreshPlaceholder();
  window.scrollTo(0, 0); // on phones the start screen may have been scrolled down
}

/** Back/forward and edited links: show whatever the address now says. */
function followAddress() {
  const wanted = readHash();
  const c = cases.find((x) => x.id === wanted.caseId);
  if (!c) { if (!document.body.classList.contains('at-home')) showHome({ push: false }); return; }
  const r = c.roles.find((x) => x.id === wanted.roleId) || c.roles[0];
  const mode = wanted.mode === 'live' && hasModel() ? 'live' : 'demo';
  // While another case is still loading, the screen is about to change: always follow the address.
  const onScreen = !document.body.classList.contains('at-home') && !document.body.classList.contains('loading')
    && state.caseId === c.id && state.roleId === r.id && state.mode === mode;
  if (!onScreen) openCase(c.id, r.id, { push: false, mode });
}

function showFatal(message) {
  document.body.classList.remove('loading');
  $('#app').replaceChildren(el('div', { className: 'fatal' },
    el('h2', { text: 'Something went wrong' }),
    el('p', { text: message }),
    el('p', { text: 'If you are running from a clone, build the corpus with `sparring-partner ingest` and serve the app with `sparring-partner serve`.' })));
}

// ------------------------------------------------------------------ actions

function wireTopbar() {
  $('#case-select').addEventListener('change', (e) => {
    const [caseId, roleId] = e.target.value.split('/');
    openCase(caseId, roleId); // a history entry, like opening it from the start screen
  });
  $('#mode-demo').addEventListener('click', () => {
    if (state.mode !== 'demo') loadSession({ caseId: state.caseId, roleId: state.roleId, mode: 'demo' });
  });
  $('#mode-live').addEventListener('click', () => {
    if (state.mode !== 'live' && hasModel()) loadSession({ caseId: state.caseId, roleId: state.roleId, mode: 'live' });
  });
  $('#reset').addEventListener('click', () => {
    if (!confirm('Start over? This clears your notes, chats and saved insights for this case and role.')) return;
    log('session_reset');
    resetSession({ clearStorage: true });
    loadSession({ caseId: state.caseId, roleId: state.roleId, mode: state.mode }, { saveCurrent: false });
  });
  $('#export').addEventListener('click', () => {
    log('session_exported');
    const data = exportSession(readNotes());
    const stamp = new Date().toISOString().replace(/[:.]/g, '-').slice(0, 19);
    download(`sparring-partner-${state.caseId}-${state.roleId}-${stamp}.json`, JSON.stringify(data, null, 2));
  });
  $('#help').addEventListener('click', () => $('#help-dialog').showModal());
  $('#home-link').addEventListener('click', () => showHome());
  window.addEventListener('popstate', followAddress);
  $('#brief-toggle').addEventListener('click', () => setBriefOpen(!$('#role-brief').hasAttribute('open')));
  window.addEventListener('beforeunload', save);
}

// ------------------------------------------------------------------ boot

async function boot() {
  window.__spBooted = true;
  initEditor({ selectGap, firstGaps: () => setBriefOpen(false) });
  initSources({ selectGap });
  initSynthesis({ selectGap });
  wireTopbar();
  wireLayout();

  await detectBackend();
  try {
    cases = await listCases();
  } catch (err) {
    showFatal(`No case index found (${err.message}).`);
    return;
  }
  if (!cases.length) { showFatal('No cases have been built yet.'); return; }

  // A link with a case in it opens that case; otherwise start on the case list.
  const wanted = readHash();
  const caseEntry = cases.find((c) => c.id === wanted.caseId);
  if (!caseEntry) {
    document.body.classList.remove('loading');
    await renderHome();
    showHome();
    welcomeOnce();
    return;
  }
  renderHome();
  const roleEntry = caseEntry.roles.find((r) => r.id === wanted.roleId) || caseEntry.roles[0];
  await loadSession({ caseId: caseEntry.id, roleId: roleEntry.id, mode: wanted.mode || 'demo' });
  refreshPlaceholder();
  welcomeOnce();
}

/** Show "How it works" the first time someone opens the app in this browser. */
function welcomeOnce() {
  let seen = true;
  try {
    seen = Boolean(localStorage.getItem('sparring-partner:seen-help'));
    localStorage.setItem('sparring-partner:seen-help', '1');
  } catch { /* storage unavailable: skip the welcome */ }
  if (!seen) $('#help-dialog').showModal();
}

boot();
